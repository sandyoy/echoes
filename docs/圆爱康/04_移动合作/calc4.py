CUT=0.10
tot={}; out=[]
for name,wan,desc in H:
    out.append("="*88)
    out.append("【%s】%s   年门诊 %.0f 万人次" % (name,desc,wan))
    out.append("-"*88)
    out.append("%-14s %8s %8s %10s %8s %8s %9s %10s" % ("项目","门诊(万)","目标人群%","目标人次(万)","人均次","居家转化","签约人数","年流水(万)"))
    tp=0; tr=0
    for d,share,tgt,per,conv,price,note in ZH[name]:
        v=wan*share
        tv=v*tgt
        heads=tv*10000/per
        signed=heads*conv
        rev=signed*price/10000
        tp+=signed; tr+=rev
        out.append("%-14s %8.1f %7.0f%% %10.2f %8.1f %7.0f%% %9.0f %10.1f" % (d,v,tgt*100,tv,per,conv*100,signed,rev))
    out.append("-"*88)
    out.append("合计：签约 %.0f 人 ｜ 年流水 %.0f 万元 ｜ 移动10%%分成 %.0f 万元" % (tp,tr,tr*CUT))
    out.append("")
    tot[name]=(tp,tr)
out.append("="*88)
tp=sum(v[0] for v in tot.values()); tr=sum(v[1] for v in tot.values())
